import json
from typing import Dict, Any
from agents.base.base_agent import BaseAgent
from tools.filesystem import write_file

class DocumentAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            name="document_agent",
            description="Generates structured Markdown, JSON, and tabular artifacts"
        )

    async def run(self, task: Dict[str, Any]) -> Dict[str, Any]:
        title = task.get("title", "untitled_artifact")
        safe_slug = "".join(c if c.isalnum() else "_" for c in title).strip("_").lower()
        filename = f"{safe_slug}.md"

        content = (
            f"# {title}\n\n"
            f"- **Generated By:** AURA DocumentAgent\n"
            f"- **Task ID:** {task.get('id', 'unknown')}\n\n"
            f"## Synthesis\n"
            f"{task.get('context', 'Autonomous synthesis completed.')}\n"
        )
        result = write_file(filename, content)

        return {
            "status": "success",
            "agent": self.name,
            "artifact_path": result["path"],
            "bytes_written": result["bytes"],
            "artifact_created": True,
        }
